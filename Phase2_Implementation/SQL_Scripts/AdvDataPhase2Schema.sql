-- Ticketing logic
CREATE TABLE PERFORMANCE_SEAT (
    id SERIAL PRIMARY KEY,
    seat_id INTEGER NOT NULL REFERENCES SEAT(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    performance_id INTEGER NOT NULL REFERENCES PERFORMANCE(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    status VARCHAR(25) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD', 'UNAVAILABLE')),
    held_until TIMESTAMPTZ,
    UNIQUE (seat_id, performance_id)
);

CREATE TABLE TICKET (
    id SERIAL PRIMARY KEY,
    performance_seat_id INTEGER UNIQUE NOT NULL REFERENCES PERFORMANCE_SEAT(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    price NUMERIC(10,2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE TICKET_SCAN (
    id SERIAL PRIMARY KEY,
    ticket_id INTEGER NOT NULL REFERENCES TICKET(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    success BOOLEAN NOT NULL
);

CREATE TABLE CART_ITEM (
    id SERIAL PRIMARY KEY,
    cart_id INTEGER NOT NULL REFERENCES CART(id) ON DELETE CASCADE ON UPDATE CASCADE,
    ticket_id INTEGER UNIQUE NOT NULL REFERENCES TICKET(id) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE "ORDER" (
    id SERIAL PRIMARY KEY,
    cart_id INTEGER NOT NULL REFERENCES CART(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    promo_code_id INTEGER REFERENCES PROMO_CODE(id) ON DELETE SET NULL ON UPDATE CASCADE,
    date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE PAYMENT (
    id SERIAL PRIMARY KEY,
    order_id INTEGER UNIQUE NOT NULL REFERENCES "ORDER"(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    method VARCHAR(50) NOT NULL CHECK (method IN ('CREDIT_CARD', 'DEBIT_CARD', 'PAYPAL', 'APPLE_PAY', 'GOOGLE_PAY', 'MASTERCARD', 'VISA')), 
    amount NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

--Indexes
CREATE INDEX idx_fk_performance_event ON PERFORMANCE(event_id);
CREATE INDEX idx_fk_performance_stage ON PERFORMANCE(stage_id);
CREATE INDEX idx_fk_perf_seat_perf ON PERFORMANCE_SEAT(performance_id);
CREATE INDEX idx_fk_order_cart ON "ORDER"(cart_id);
CREATE INDEX idx_fk_audit_staff ON AUDIT_LOG(staff_id);
CREATE INDEX idx_fk_error_person ON ERROR_LOG(person_id);

CREATE INDEX idx_perf_seat_status ON PERFORMANCE_SEAT(status);
CREATE INDEX idx_event_status ON EVENT(status);
CREATE INDEX idx_error_endpoint ON ERROR_LOG(end_point);
CREATE INDEX idx_order_date ON "ORDER"(date_time);
CREATE INDEX idx_promo_active ON PROMO_CODE(active);
CREATE INDEX idx_event_dates ON EVENT(live_date);
CREATE INDEX idx_audit_table ON AUDIT_LOG(table_name, record_id);
