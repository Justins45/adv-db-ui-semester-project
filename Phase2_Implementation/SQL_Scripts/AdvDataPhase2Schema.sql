-- BASE ENTITIES
CREATE TABLE ROLE (
    id SERIAL PRIMARY KEY,
    role VARCHAR(50) UNIQUE NOT NULL CHECK (role IN ('ADMIN', 'STAFF', 'PATRON'))
);

CREATE TABLE PERSON (
    id SERIAL PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL CHECK (email LIKE '%@%'),
    phone VARCHAR(20) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL
);

CREATE TABLE VENUE (
    id SERIAL PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    address VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    province VARCHAR(50) NOT NULL,
    postal_code VARCHAR(20) NOT NULL
);

CREATE TABLE EVENT (
    id SERIAL PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    live_date TIMESTAMPTZ,
    image BYTEA
);

CREATE TABLE GENRE (
    id SERIAL PRIMARY KEY,
    name VARCHAR(50) UNIQUE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE PROMO_CODE (
    id SERIAL PRIMARY KEY,
    code VARCHAR(50) UNIQUE NOT NULL,
    d_off NUMERIC(10,2),
    p_off NUMERIC(5,2) CHECK (p_off >= 0 AND p_off <= 1),
    active BOOLEAN NOT NULL DEFAULT TRUE, 
    expiry_date TIMESTAMPTZ
);

-- first level dependencies 
CREATE TABLE EMAIL_LIST (
    person_id INTEGER PRIMARY KEY REFERENCES PERSON(id) ON DELETE CASCADE ON UPDATE CASCADE,
    added TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE LOGIN_HISTORY (
    id SERIAL PRIMARY KEY,
    person_id INTEGER NOT NULL REFERENCES PERSON(id) ON DELETE CASCADE ON UPDATE CASCADE,
    ip_address VARCHAR(50) NOT NULL,
    success BOOLEAN NOT NULL,
    login_timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ERROR_LOG (
    id SERIAL PRIMARY KEY,
    person_id INTEGER REFERENCES PERSON(id) ON DELETE SET NULL ON UPDATE CASCADE,
    end_point VARCHAR(255) NOT NULL,
    error_message VARCHAR(500) NOT NULL,
    stack_trace BYTEA,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE PASSWORD_RESET_REQUEST (
    id SERIAL PRIMARY KEY,
    person_id INTEGER NOT NULL REFERENCES PERSON(id) ON DELETE CASCADE ON UPDATE CASCADE,
    time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    success BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'COMPLETED', 'EXPIRED', 'FAILED'))
);

CREATE TABLE PATRON (
    id INTEGER PRIMARY KEY REFERENCES PERSON(id) ON DELETE CASCADE ON UPDATE CASCADE,
    role_id INTEGER NOT NULL REFERENCES ROLE(id) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE STAFF (
    id INTEGER PRIMARY KEY REFERENCES PERSON(id) ON DELETE CASCADE ON UPDATE CASCADE,
    role_id INTEGER NOT NULL REFERENCES ROLE(id) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE PERFORMER (
    id INTEGER PRIMARY KEY REFERENCES PERSON(id) ON DELETE CASCADE ON UPDATE CASCADE,
    role VARCHAR(50)
);

CREATE TABLE STAGE (
    id SERIAL PRIMARY KEY,
    venue_id INTEGER NOT NULL REFERENCES VENUE(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    name VARCHAR(50) NOT NULL
);

CREATE TABLE EVENT_GENRE (
    genre_id INTEGER REFERENCES GENRE(id) ON DELETE CASCADE ON UPDATE CASCADE,
    event_id INTEGER REFERENCES EVENT(id) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (genre_id, event_id)
);

--second level dependent entities
CREATE TABLE PERMISSION_CHANGE_LOG (
    id SERIAL PRIMARY KEY,
    person_id INTEGER NOT NULL REFERENCES PERSON(id) ON DELETE CASCADE ON UPDATE CASCADE,
    changed_by INTEGER NOT NULL REFERENCES PERSON(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    old_role INTEGER NOT NULL REFERENCES ROLE(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    new_role INTEGER NOT NULL REFERENCES ROLE(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE AUDIT_LOG (
    id SERIAL PRIMARY KEY,
    staff_id INTEGER NOT NULL REFERENCES STAFF(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    table_name VARCHAR(50) NOT NULL,
    record_id INTEGER NOT NULL,
    action VARCHAR(50) NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    old_value BYTEA,
    new_value BYTEA,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ip_address VARCHAR(45) NOT NULL
);

CREATE TABLE CART (
    id SERIAL PRIMARY KEY,
    patron_id INTEGER NOT NULL REFERENCES PATRON(id) ON DELETE CASCADE ON UPDATE CASCADE,
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CHECKED_OUT', 'ABANDONED'))
);

CREATE TABLE SECTION (
    id SERIAL PRIMARY KEY,
    stage_id INTEGER NOT NULL REFERENCES STAGE(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    name VARCHAR(50) NOT NULL
);

CREATE TABLE PERFORMANCE (
    id SERIAL PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES EVENT(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    stage_id INTEGER NOT NULL REFERENCES STAGE(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    date_time TIMESTAMPTZ NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('DRAFT', 'SCHEDULED', 'CANCELLED', 'COMPLETED')),
    filled BOOLEAN NOT NULL DEFAULT FALSE
);

-- third level dependent entities
CREATE TABLE SEAT (
    id SERIAL PRIMARY KEY,
    section_id INTEGER NOT NULL REFERENCES SECTION(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    row VARCHAR(5) NOT NULL,
    seat_number INTEGER NOT NULL,
    UNIQUE (section_id, row, seat_number) 
);

CREATE TABLE PERFORMANCE_STATUS_LOG (
    id SERIAL PRIMARY KEY,
    performance_id INTEGER NOT NULL REFERENCES PERFORMANCE(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    changed_by INTEGER NOT NULL REFERENCES PERSON(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    previous VARCHAR(50) NOT NULL CHECK (previous IN ('DRAFT', 'SCHEDULED', 'CANCELLED', 'COMPLETED')),
    new VARCHAR(50) NOT NULL CHECK (new IN ('DRAFT', 'SCHEDULED', 'CANCELLED', 'COMPLETED')),
    date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE PERFORMANCE_CAST (
    performer_id INTEGER NOT NULL REFERENCES PERFORMER(id) ON DELETE CASCADE ON UPDATE CASCADE,
    performance_id INTEGER NOT NULL REFERENCES PERFORMANCE(id) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (performer_id, performance_id)
);

CREATE TABLE PRICE_TIER (
    id SERIAL PRIMARY KEY,
    section_id INTEGER REFERENCES SECTION(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    performance_id INTEGER REFERENCES PERFORMANCE(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    stage_id INTEGER REFERENCES STAGE(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    event_id INTEGER REFERENCES EVENT(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    price NUMERIC(10,2) NOT NULL CHECK (price >= 0)
);
